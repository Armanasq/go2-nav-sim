#!/usr/bin/env python3
"""Write pyrightconfig.json so the editor (Pylance/pyright) resolves this repository's imports.
usage: python3 tools/pyright_envs.py [--parent]   (rerun after adding a folder under tasks/, projects/ or modules/;
       --parent also writes ../pyrightconfig.json for an editor whose workspace is the folder above this repository)
Scripts here import ROS 2 Humble, the .venv-modules packages (mujoco, pinocchio) and modules from sibling folders, which
they put on sys.path at run time. One execution environment per folder keeps same-named files apart (every tasks/ stage
has its own lib.py and run.py). Editor-only: nothing at run time reads this file."""
import glob, json, os, sys

ROS = ["/opt/ros/humble/lib/python3.10/site-packages", "/opt/ros/humble/local/lib/python3.10/dist-packages"]
EXTRA = [".venv-modules/lib/python3.10/site-packages/cmeel.prefix/lib/python3.10/site-packages",   # pinocchio
         os.path.expanduser("~/.venv/lib/python3.10/site-packages")]                               # cv2, playwright
SHARED = (["modules"] + sorted(glob.glob("modules/m*_*")) + ["src/go2_nav_sim/scripts", "projects/common"]
          + ["projects/p02_teleop-and-safety", "projects/p03_move-in-shapes", "projects/p04_go-to-pose",
             "projects/p05_sense-and-stop", "projects/p06_avoid-obstacles", "projects/p07_build-a-map"])           # helpers that later tasks import (measure_stop, shapes, polar, obstacle, reactive, arena2d, mapcmp)
SKIP = {"__pycache__", "results", "figures", "media", "tests"}


def pydirs(root):
    """root and its sub-folders that hold Python files"""
    out = []
    for d, sub, files in os.walk(root):
        sub[:] = [s for s in sub if s not in SKIP]
        if any(f.endswith(".py") for f in files):
            out.append(d)
    return out or [root]


EXCLUDE = ["build", "install", "log", "logs", "overlay", "_site", "site/dev", "src/third_party", ".venv-modules", "bags"]


def config(pre):
    """pre = '' for this repository opened as the workspace, 'go2-nav-sim/' for the parent folder opened as the workspace
    (there no venv is set, so other projects in the parent keep the interpreter selected in the editor)."""
    venv_pkgs = [pre + ".venv-modules/lib/python3.10/site-packages"] if pre else []
    extra = [p if p.startswith("/") else pre + p for p in EXTRA] + venv_pkgs
    roots = [r.rstrip("/") for r in sorted(glob.glob("tasks/s*/") + glob.glob("projects/p*/") + glob.glob("modules/m*_*/"))]
    roots += [r for r in ("projects/common", "src/go2_nav_sim", "src/go2_tutorials", "tools", "site", "docs") if os.path.isdir(r)]
    envs = [{"root": pre + r, "extraPaths": [pre + p for p in pydirs(r) + [s for s in SHARED if s != r]] + ROS + extra}
            for r in roots]
    envs.append({"root": pre or ".", "extraPaths": [pre + s for s in SHARED] + ROS + extra})
    cfg = {"//": "generated by go2-nav-sim/tools/pyright_envs.py; editor-only import paths",
           "pythonVersion": "3.10", "stubPath": pre + "typings", "extraPaths": ROS + extra,   # library files outside the project use the top-level paths
           "exclude": [pre + e for e in EXCLUDE] + ["**/__pycache__", "**/node_modules", "**/.*"],
           "executionEnvironments": envs}
    if not pre:
        cfg.update(venvPath=".", venv=".venv-modules")
    return cfg


def main():
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    targets = [("pyrightconfig.json", "")]
    if "--parent" in sys.argv:   # the editor workspace is the folder above this repository
        targets.append((os.path.join("..", "pyrightconfig.json"), os.path.basename(os.getcwd()) + "/"))
    for path, pre in targets:
        cfg = config(pre)
        with open(path, "w") as f:
            json.dump(cfg, f, indent=1)
        print(f"{os.path.abspath(path)}: {len(cfg['executionEnvironments'])} environments")


if __name__ == "__main__":
    main()
